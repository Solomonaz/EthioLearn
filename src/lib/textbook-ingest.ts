/**
 * Textbook ingestion: turning an uploaded book file into chapters.
 *
 * Two callers share it:
 *   • create-with-ai — the super admin's interactive upload, which returns the
 *     detected chapters for review before anything is saved.
 *   • the approval job — a school's request, held on disk until a super admin
 *     approves it, then ingested in the background. Nothing paid (the AI
 *     chapter detection) runs before that approval.
 */

// ─── File storage for pending requests ───────────────────

export const TEXTBOOK_EXTENSIONS = ["pdf", "docx", "doc", "epub"] as const;
export const MAX_TEXTBOOK_BYTES = 50 * 1024 * 1024;

const TEXTBOOK_DIR = path.join(UPLOAD_ROOT, "textbooks");

/** Leading bytes each accepted type must carry — the extension alone is client-controlled. */
function looksLike(ext: string, buf: Buffer): boolean {
  const starts = (sig: number[]) => sig.every((b, i) => buf[i] === b);
  if (ext === "pdf") return starts([0x25, 0x50, 0x44, 0x46]); // %PDF
  if (ext === "docx" || ext === "epub") return starts([0x50, 0x4b, 0x03, 0x04]); // zip
  if (ext === "doc") return starts([0xd0, 0xcf, 0x11, 0xe0]); // OLE compound file
  return false;
}

export function textbookFileExt(fileName: string): string | null {
  const ext = fileName.toLowerCase().split(".").pop() ?? "";
  return (TEXTBOOK_EXTENSIONS as readonly string[]).includes(ext) ? ext : null;
}

/** Saves a request's file under a generated name. Returns the stored key. */
export async function storeTextbookFile(buffer: Buffer, fileName: string): Promise<string> {
  const ext = textbookFileExt(fileName);
  if (!ext) throw new Error("Please upload a PDF, DOCX, DOC, or EPUB file.");
  if (buffer.length > MAX_TEXTBOOK_BYTES) throw new Error("File too large. Maximum size is 50 MB.");
  if (!looksLike(ext, buffer)) throw new Error(`That file is not a valid .${ext} document.`);
  await mkdir(TEXTBOOK_DIR, { recursive: true });
  const key = `${randomUUID()}.${ext}`;
  await writeFile(path.join(TEXTBOOK_DIR, key), buffer);
  return key;
}

function keyPath(key: string): string {
  // Keys are generated by storeTextbookFile; refuse anything else.
  if (!/^[0-9a-f-]{36}\.(pdf|docx|doc|epub)$/.test(key)) throw new Error("Invalid file key");
  return path.join(TEXTBOOK_DIR, key);
}

export async function readTextbookFile(key: string): Promise<Buffer> {
  return readFile(keyPath(key));
}

export async function deleteTextbookFile(key: string | null | undefined): Promise<void> {
  if (!key) return;
  try {
    await unlink(keyPath(key));
  } catch {
    /* already gone — nothing to clean up */
  }
}

// ─── Extraction + chapter detection ──────────────────────

export interface DetectedChapterWithContent {
  chapterNumber: number;
  title: string;
  content: string;
}

export interface IngestResult {
  extraction: ExtractionResult;
  chapters: DetectedChapterWithContent[];
  warnings: string[];
}

export async function extractAndDetectChapters(
  buffer: Buffer,
  fileName: string,
  meta: { subject: string; grade: number; language?: string },
): Promise<IngestResult> {
  // 1. Extract text (local parsing / Tesseract OCR — no paid API).
  const extraction = await extractTextFromFile(buffer, fileName);

  // 2. Detect chapters across the WHOLE document — windowed AI passes plus a
  // deterministic heading sweep, unioned (see lib/chapter-detection).
  let detected: { chapterNumber: number; title: string }[];
  let detectionWarnings: string[] = [];
  try {
    const result = await detectChaptersFullText({
      content: extraction.text,
      subject: await canonicalSubject(meta.subject),
      grade: meta.grade,
      language: meta.language ?? "en",
    });
    detected = result.chapters;
    detectionWarnings = result.warnings;
    console.log(
      `[Ingest] Detection: ${result.chapters.length} chapters via ${result.provider} ` +
        `(strategy: ${result.strategy}, ${result.windowsScanned} AI call(s)); ` +
        `${result.recoveredByScan} recovered by scan.`,
    );
  } catch (aiError) {
    console.warn("[Ingest] AI chapter detection failed. Falling back to single chapter.", aiError);
    detected = [{ chapterNumber: 1, title: "Full Textbook Content" }];
    detectionWarnings = [
      "Automatic chapter detection failed — the whole book was kept as a single chapter. Split it manually before generating questions.",
    ];
  }

  // 3. Split text by chapter boundaries. The raw title locates each chapter in
  // the text; only the finished list is cleaned to one consistent form.
  const chapters = splitTextByChapters(extraction.text, detected).map((ch) => ({
    chapterNumber: ch.chapterNumber,
    title: cleanChapterTitle(ch.title),
    content: ch.content,
  }));

  return { extraction, chapters, warnings: [...(extraction.warnings ?? []), ...detectionWarnings] };
}

// ─── Background job for an approved request ──────────────

/** A run longer than this is treated as dead (hung OCR worker, server restart). */
export const INGEST_TIMEOUT_MS = 15 * 60 * 1000;

function withTimeout<T>(p: Promise<T>, ms: number): Promise<T> {
  return new Promise<T>((resolve, reject) => {
    const t = setTimeout(() => reject(new Error("Timed out while reading the book. Try again, or re-upload a text-based PDF.")), ms);
    p.then(
      (v) => { clearTimeout(t); resolve(v); },
      (e) => { clearTimeout(t); reject(e); },
    );
  });
}

/**
 * Ingests an approved school request: reads the held file, detects chapters,
 * saves them, and tells the school. Runs after the approval response has been
 * sent; failures are recorded on the textbook so the super admin can retry.
 */
export async function ingestApprovedTextbook(textbookId: string): Promise<void> {
  const tb = await db.textbook.findUnique({
    where: { id: textbookId },
    select: {
      id: true,
      title: true,
      subject: true,
      grade: true,
      language: true,
      approvalStatus: true,
      sourceFile: true,
      sourceFileName: true,
      uploadedById: true,
      _count: { select: { chapters: true } },
    },
  });
  if (!tb || tb.approvalStatus !== "APPROVED" || !tb.sourceFile) return;
  // A retry after a partial success must not stack a second set of chapters.
  if (tb._count.chapters > 0) {
    await db.textbook.update({
      where: { id: tb.id },
      data: { processingStatus: "COMPLETED", processingError: null },
    });
    return;
  }

  try {
    const buffer = await readTextbookFile(tb.sourceFile);
    const { extraction, chapters, warnings } = await withTimeout(
      extractAndDetectChapters(buffer, tb.sourceFileName ?? tb.sourceFile, {
        subject: tb.subject,
        grade: tb.grade,
        language: tb.language,
      }),
      INGEST_TIMEOUT_MS,
    );

    await db.$transaction([
      db.chapter.createMany({
        data: chapters.map((ch) => ({
          textbookId: tb.id,
          chapterNumber: ch.chapterNumber,
          title: ch.title,
          content: ch.content || undefined,
        })),
      }),
      db.textbook.update({
        where: { id: tb.id },
        data: {
          content: extraction.text || undefined,
          chapterCount: chapters.length,
          processingStatus: "COMPLETED",
          processingError: null,
        },
      }),
    ]);

    // The text now lives in the database — the held file has done its job.
    await deleteTextbookFile(tb.sourceFile);
    await db.textbook.update({ where: { id: tb.id }, data: { sourceFile: null } });

    if (tb.uploadedById) {
      await createNotification(
        tb.uploadedById,
        "system",
        "Textbook approved and ready",
        `"${tb.title}" was approved. ${chapters.length} chapter${chapters.length !== 1 ? "s were" : " was"} detected` +
          (warnings.length ? " — please review the chapters." : "."),
        { textbookId: tb.id, href: "/school-admin/textbooks" },
      ).catch(() => {});
    }
  } catch (err) {
    const message = err instanceof Error ? err.message : "Processing failed";
    console.error(`[Ingest] Failed for textbook ${tb.id}:`, err);
    await db.textbook.update({
      where: { id: tb.id },
      data: { processingStatus: "FAILED", processingError: message.slice(0, 500) },
    });
  }
}
